// Builds www/quick_capture/common-words.js (everyday English words for "전공용어 위주") and
// www/quick_capture/english-words.js (dictionary for repairing OCR words) and
// www/quick_capture/word-tiers.js (how common words are, for ranking)
// from SCOWL size 10 as packaged by wordlist-english (MIT wrapper; SCOWL permissive licence,
// copied to www/vendor/scowl/Copyright.txt).
// Run once after installing the package somewhere outside the app, e.g.:
//   npm install --no-save wordlist-english@1.2.1
//   node scripts/build-common-words.cjs node_modules/wordlist-english
const fs = require('node:fs');
const path = require('node:path');

const source = path.resolve(process.argv[2] || 'node_modules/wordlist-english');
const version = require(path.join(source, 'package.json')).version;
const words = [...new Set(require(path.join(source, 'english-words-10.json'))
  .map(word => word.toLowerCase()).filter(word => /^[a-z]+$/.test(word)))].sort();
const body = `// Everyday English words for "전공용어 위주" (PDF·사진에서 단어 찾기): SCOWL size 10
// (wordlist-english ${version}, english-words-10), ${words.length} words incl. inflected forms.
// Copyright 2000-2016 Kevin Atkinson; permissive licence, see vendor/scowl/Copyright.txt.
// Generated by scripts/build-common-words.cjs — do not edit by hand.
(function(root) {
  "use strict";
  const words = ${JSON.stringify(words.join(' '))}.split(" ");
  if (typeof module !== "undefined" && module.exports) module.exports = words;
  root.WordCollectorCommonWords = words;
})(typeof globalThis !== "undefined" ? globalThis : this);
`;
fs.writeFileSync(path.join(__dirname, '..', 'www', 'quick_capture', 'common-words.js'), body);
console.log(`${words.length} words → www/quick_capture/common-words.js`);

// The larger list (SCOWL sizes 10–70, all spellings) used only to repair words cut off by
// the character recognition ("apacitance" → "capacitance"); loaded only when OCR runs.
const all = new Set();
for (const size of [10, 20, 35, 40, 50, 55, 60, 70]) {
  // All spellings (American "vapor", British "vapour", Canadian, Australian).
  for (const variant of ['english', 'american', 'british', 'canadian', 'australian']) {
    for (const word of require(path.join(source, `${variant}-words-${size}.json`))) if (/^[a-z]+$/i.test(word)) all.add(word.toLowerCase());
  }
}
const dictionary = [...all].sort();
fs.writeFileSync(path.join(__dirname, '..', 'www', 'quick_capture', 'english-words.js'),
`// English dictionary for repairing OCR words (PDF·사진에서 단어 찾기): SCOWL sizes 10–70, all spellings
// (wordlist-english ${version}), ${dictionary.length} words. Copyright 2000-2016 Kevin Atkinson;
// permissive licence, see vendor/scowl/Copyright.txt. Generated by scripts/build-common-words.cjs.
(function(root) {
  "use strict";
  const words = ${JSON.stringify(dictionary.join(' '))}.split(" ");
  if (typeof module !== "undefined" && module.exports) module.exports = words;
  root.WordCollectorEnglishWords = words;
})(typeof globalThis !== "undefined" ? globalThis : this);
`);
console.log(`${dictionary.length} words → www/quick_capture/english-words.js`);

// How common a word is (for ranking candidates, "전공용어일 가능성"): SCOWL size 20 and size 35
// words not already in size 10 (common-words.js). Words in none of them count as rare.
const tierWords = size => {
  const words = new Set();
  for (const variant of ['english', 'american', 'british', 'canadian', 'australian']) {
    for (const word of require(path.join(source, `${variant}-words-${size}.json`))) if (/^[a-z]+$/i.test(word)) words.add(word.toLowerCase());
  }
  return words;
};
const size10 = new Set(words);
const tier20 = [...tierWords(20)].filter(word => !size10.has(word)).sort();
const tier35 = [...tierWords(35)].filter(word => !size10.has(word) && !tier20.includes(word)).sort();
fs.writeFileSync(path.join(__dirname, '..', 'www', 'quick_capture', 'word-tiers.js'),
`// How common English words are, for ranking candidates (PDF·사진에서 단어 찾기): SCOWL size 20
// (${tier20.length} words) and size 35 (${tier35.length} words) beyond size 10 (common-words.js).
// wordlist-english ${version}; Copyright 2000-2016 Kevin Atkinson; see vendor/scowl/Copyright.txt.
// Generated by scripts/build-common-words.cjs — do not edit by hand.
(function(root) {
  "use strict";
  const tiers = {20: ${JSON.stringify(tier20.join(' '))}.split(" "), 35: ${JSON.stringify(tier35.join(' '))}.split(" ")};
  if (typeof module !== "undefined" && module.exports) module.exports = tiers;
  root.WordCollectorWordTiers = tiers;
})(typeof globalThis !== "undefined" ? globalThis : this);
`);
console.log(`${tier20.length} + ${tier35.length} words → www/quick_capture/word-tiers.js`);
