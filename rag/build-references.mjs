// Builds www/references.html ("참고 자료") from rag/sources.json: the registered
// textbooks and papers used as reference material for the analysis, with their
// authors, edition, licence and attribution. Run after changing sources.json:
//   node rag/build-references.mjs
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const root = new URL('..', import.meta.url);
const {sources} = JSON.parse(readFileSync(new URL('rag/sources.json', root), 'utf8'));
const esc = value => String(value ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const link = (url, text) => url ? `<a href="${esc(url)}" target="_blank" rel="noopener noreferrer">${esc(text || url)}</a>` : esc(text);
const TYPE = {textbook: '교재', paper: '논문', slides: '강의 자료', book: '교재', dictionary: '사전'};

export function registered() {
  return sources.filter(source => source.register === true);
}

// Korean dictionaries used to check the glossary's Korean meanings (not File Search material).
export function dictionaries() {
  return sources.filter(source => source.type === 'dictionary');
}

function item(s) {
  return `
    <li class="ref" data-source-id="${esc(s.id)}">
      <p class="title">${esc(s.title)}</p>
      <p class="meta">${esc(s.author)}${s.publisher && s.publisher !== s.author ? ' · ' + esc(s.publisher) : ''}</p>
      <p class="meta">${esc(TYPE[s.type] || s.type || '자료')}${s.edition ? ' · ' + esc(s.edition) : ''}</p>
      <p class="meta">라이선스: ${link(s.licenseUrl, s.license)}</p>
      ${s.url ? `<p class="meta">원문: ${link(s.url)}</p>` : ''}
    </li>`;
}

export function render() {
  const fields = [...new Set(registered().map(s => s.field))];
  const sections = fields.map(field => {
    const items = registered().filter(s => s.field === field).map(item).join('');
    return `<section class="panel"><h2>${esc(field)} <span class="count">${registered().filter(s => s.field === field).length}개</span></h2><ul class="refs">${items}
  </ul></section>`;
  }).join('\n') + (dictionaries().length ? `
<section class="panel"><h2>국어사전 <span class="count">${dictionaries().length}개</span></h2><p class="intro">단어의 한국어 뜻과 전문용어를 확인하는 데 쓰는 국립국어원 사전입니다.</p><ul class="refs">${dictionaries().map(item).join('')}
  </ul></section>` : '');
  return `<!doctype html>
<html lang="ko"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover"><script src="./screen-scale.js"></script><script src="./native-back.js"></script><title>참고 자료 · Word Collector</title>
<!-- Generated by rag/build-references.mjs from rag/sources.json. Do not edit by hand. -->
<style>
:root{font-family:system-ui,'Malgun Gothic',sans-serif;color:#131b2e;background:#faf8ff}*{box-sizing:border-box}body{margin:0;min-height:100vh;background:#faf8ff}
header{position:sticky;top:0;padding:calc(12px + env(safe-area-inset-top,0px)) 16px 12px;background:white;border-bottom:1px solid #e2e7ff;display:flex;align-items:center;gap:12px;z-index:1}
header a.back{color:#00236f;text-decoration:none;font-size:22px;line-height:1;width:36px;height:36px;display:flex;align-items:center;justify-content:center;border-radius:50%}
header img{width:32px;height:32px;border-radius:8px}h1{font-size:19px;margin:0}
main{max-width:640px;margin:auto;padding:16px 16px calc(40px + env(safe-area-inset-bottom,0px))}
.intro{font-size:14px;line-height:1.65;color:#444b5c;margin:0 0 14px}
.panel{background:white;border:1px solid #e2e7ff;border-radius:14px;padding:16px;margin-bottom:14px}
h2{font-size:16px;margin:0 0 6px;color:#00236f}.count{font-size:13px;color:#757c8f;font-weight:500}
.refs{list-style:none;margin:0;padding:0}.ref{padding:12px 0;border-top:1px solid #eef0f8}.ref:first-child{border-top:0}
.title{font-weight:650;font-size:14.5px;margin:0 0 4px;line-height:1.45;overflow-wrap:anywhere}
.meta{font-size:13px;color:#555e70;margin:2px 0;line-height:1.5;overflow-wrap:anywhere}
.attr{font-size:12px;color:#757c8f;margin:4px 0 2px;line-height:1.5;overflow-wrap:anywhere}
a{color:#00497d}
</style><link rel="apple-touch-icon" sizes="192x192" href="icons/apple-touch-icon.png"><link rel="icon" href="icons/wordcollector-app-icon.webp" type="image/webp"></head><body>
<header><a class="back" href="index.html" aria-label="홈으로">&larr;</a><img src="icons/wordcollector-app-icon.webp" alt="워드콜렉터 로고"><h1>참고 자료</h1></header>
<main>
<p class="intro">Word Collector가 전공 단어를 분석할 때 근거로 참고한 교재와 논문입니다(${registered().length}개). 앱의 뜻·정의·예문은 이 자료를 참고해 AI가 새로 작성한 것이며, 자료의 원문을 그대로 옮기지 않았습니다. 각 자료의 저작권은 표시된 저작자와 라이선스를 따릅니다.</p>
${sections}
</main></body></html>
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL('www/references.html', root), render());
  console.log('wrote www/references.html with', registered().length, 'sources');
}
